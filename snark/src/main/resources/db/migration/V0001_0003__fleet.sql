CREATE TABLE IF NOT EXISTS fleet(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL,
    target_galaxy INT,
    target_system INT,
    target_position INT,
    space_target TEXT,
    source_id BIGINT NOT NULL REFERENCES colonies,
    start TIMESTAMP DEFAULT NULL,
    visited TIMESTAMP DEFAULT NULL,
    back TIMESTAMP DEFAULT NULL,
    speed BIGINT,
    metal BIGINT,
    crystal BIGINT,
    deuterium BIGINT,
    acs_code TEXT,
    code BIGINT,
    hash_code TEXT,
    updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    lm INT DEFAULT 0,
    cm INT DEFAULT 0,
    kr INT DEFAULT 0,
    ow INT DEFAULT 0,
    pan INT DEFAULT 0,
    bom INT DEFAULT 0,
    ni INT DEFAULT 0,
    gs INT DEFAULT 0,
    re INT DEFAULT 0,
    pf INT DEFAULT 0,
    lt INT DEFAULT 0,
    dt INT DEFAULT 0,
    kol INT DEFAULT 0,
    rec INT DEFAULT 0,
    son INT DEFAULT 0
);
