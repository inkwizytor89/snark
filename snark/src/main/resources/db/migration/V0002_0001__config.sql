CREATE TABLE IF NOT EXISTS modules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE DEFAULT 'global',
    time VARCHAR(255) NOT NULL DEFAULT 'on',
    conditions TEXT NOT NULL DEFAULT '',
    updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS threads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL DEFAULT 'main',
    module_id BIGINT NOT NULL REFERENCES modules(id),
    "type" TEXT NOT NULL DEFAULT 'fleet',
    time VARCHAR(255) NOT NULL DEFAULT 'off',
    conditions TEXT NOT NULL DEFAULT '',
    pause VARCHAR(255) NOT NULL DEFAULT 'off',
    debug VARCHAR(255) NOT NULL DEFAULT 'false',
    command_limit VARCHAR(255) NOT NULL DEFAULT '-1',
    updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    created_on TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_threads_module_name UNIQUE (module_id, name)
);

CREATE TABLE IF NOT EXISTS config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id BIGINT NOT NULL REFERENCES threads(id),
    "key" TEXT NOT NULL,
    "value" TEXT NOT NULL,
    updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_config_thread_key UNIQUE (thread_id, "key")
);

